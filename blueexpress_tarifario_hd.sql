-- Vista con función de cálculo de tarifa real por peso
-- Uso: SELECT calcular_envio_hd('SANTIAGO', 1.2) → tarifa para 1.2 kg a Santiago
CREATE OR REPLACE FUNCTION calcular_envio_hd(p_comuna TEXT, p_peso_kg NUMERIC)
RETURNS INTEGER AS $$
DECLARE
    t blueexpress_tarifario_hd%ROWTYPE;
    resultado INTEGER;
BEGIN
    SELECT * INTO t FROM blueexpress_tarifario_hd
    WHERE UPPER(TRIM(comuna)) = UPPER(TRIM(p_comuna))
    LIMIT 1;

    IF NOT FOUND THEN RETURN NULL; END IF;

    IF    p_peso_kg <= 0.5  THEN resultado := t.kg_0_05;
    ELSIF p_peso_kg <= 1.5  THEN resultado := t.kg_05_15;
    ELSIF p_peso_kg <= 3    THEN resultado := t.kg_15_3;
    ELSIF p_peso_kg <= 6    THEN resultado := t.kg_3_6;
    ELSIF p_peso_kg <= 10   THEN resultado := t.kg_6_10;
    ELSIF p_peso_kg <= 16   THEN resultado := t.kg_10_16;
    ELSIF p_peso_kg <= 25   THEN resultado := t.kg_16_25;
    ELSIF p_peso_kg <= 50   THEN resultado := t.kg_16_25 + CEIL((p_peso_kg - 25) * t.kg_25_50_xkg);
    ELSE                         resultado := t.kg_16_25 + CEIL(25 * t.kg_25_50_xkg) + CEIL((p_peso_kg - 50) * t.kg_mas50_xkg);
    END IF;

    RETURN resultado;
END;
$$ LANGUAGE plpgsql;

-- =============================================================
-- Vista: costo de envío real por pedido
-- Combina shopify_pedidos + shopify_lineas_pedido + shopify_products
-- + blueexpress_tarifario_hd para mostrar el costo estimado de cada envío.
-- =============================================================
CREATE OR REPLACE VIEW v_costo_envio_pedidos AS
WITH pesos AS (
    SELECT
        lp.order_id,
        lp.titulo,
        lp.cantidad,
        sp.largo_cm,
        sp.ancho_cm,
        sp.alto_cm,
        sp.peso_fisico_g,
        -- Peso volumétrico en gramos: (L*A*H)/4000 * 1000
        CASE
            WHEN sp.largo_cm IS NOT NULL AND sp.ancho_cm IS NOT NULL AND sp.alto_cm IS NOT NULL
            THEN (sp.largo_cm * sp.ancho_cm * sp.alto_cm) / 4.0
            ELSE NULL
        END AS peso_vol_g,
        CASE
            WHEN sp.peso_fisico_g IS NOT NULL
                 AND sp.largo_cm IS NOT NULL AND sp.ancho_cm IS NOT NULL AND sp.alto_cm IS NOT NULL
            THEN GREATEST(sp.peso_fisico_g, (sp.largo_cm * sp.ancho_cm * sp.alto_cm) / 4.0)
            ELSE sp.peso_fisico_g
        END AS peso_efectivo_unitario_g
    FROM shopify_lineas_pedido lp
    LEFT JOIN shopify_products sp
        ON UPPER(TRIM(sp.title)) = UPPER(TRIM(lp.titulo))
),
pesos_pedido AS (
    SELECT
        order_id,
        SUM(peso_efectivo_unitario_g * COALESCE(cantidad, 1)) AS peso_efectivo_total_g,
        SUM(peso_fisico_g * COALESCE(cantidad, 1))            AS peso_fisico_total_g,
        SUM(peso_vol_g * COALESCE(cantidad, 1))               AS peso_vol_total_g,
        COUNT(*) FILTER (WHERE peso_efectivo_unitario_g IS NULL) AS items_sin_dimensiones
    FROM pesos
    GROUP BY order_id
)
SELECT
    p.shopify_id                                        AS order_id,
    p.created_at                                        AS fecha,
    p.ciudad_envio                                      AS comuna,
    pp.peso_fisico_total_g,
    pp.peso_vol_total_g,
    pp.peso_efectivo_total_g,
    ROUND((pp.peso_efectivo_total_g / 1000.0)::numeric, 3) AS peso_efectivo_kg,
    calcular_envio_hd(
        p.ciudad_envio,
        pp.peso_efectivo_total_g / 1000.0
    )                                                   AS costo_envio_clp,
    pp.items_sin_dimensiones,
    p.total_precio                                      AS total_pedido_clp
FROM shopify_pedidos p
JOIN pesos_pedido pp ON pp.order_id = p.shopify_id;
